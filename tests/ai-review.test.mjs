import assert from "node:assert/strict";
import test from "node:test";
import { normalizeFindings, normalizeScout } from "../lib/ai-review-normalize.ts";
import { findingAnchor, findingToCommentBody, findingsAtNewLine, isFindingStaged, sortFindings } from "../lib/review-findings.ts";
import { parseUnifiedDiff } from "../lib/diff.ts";

const paths = new Set(["src/math.ts"]);
const diff = `diff --git a/src/math.ts b/src/math.ts
index 1111111..2222222 100644
--- a/src/math.ts
+++ b/src/math.ts
@@ -1,3 +1,4 @@
 export function total(values: number[]) {
-  return values.length;
+  const valid = values.filter(Number.isFinite);
+  return valid.reduce((sum, value) => sum + value, 0);
 }
`;

test("normalizes scout output to paths and risk levels in the diff", () => {
  assert.deepEqual(normalizeScout({
    intent: " Improve totals. ",
    focus_areas: [
      { file: "src/math.ts", reason: "Core behavior", risk: "high" },
      { file: "src/missing.ts", reason: "Invented", risk: "low" },
      { file: "src/math.ts", reason: "Invalid risk", risk: "urgent" },
    ],
  }, paths), {
    intent: "Improve totals.",
    focusAreas: [{ file: "src/math.ts", reason: "Core behavior", risk: "high" }],
  });
});

test("drops malformed findings and sorts usable findings by severity", () => {
  const findings = normalizeFindings([
    { file: "src/math.ts", line: 3.8, severity: "low", category: "test", title: "Tests", description: "Add coverage", suggestion: "Exercise NaN." },
    { file: "src/math.ts", line: 2, severity: "critical", category: "correctness", title: "Wrong result", description: "Breaks totals", suggestion: "Fix it." },
    { file: "src/other.ts", line: 1, severity: "high", category: "bug", title: "Invented", description: "", suggestion: "" },
  ], paths);

  assert.deepEqual(sortFindings(findings).map((finding) => finding.title), ["Wrong result", "Tests"]);
  assert.match(findingToCommentBody(findings[0]), /Generated by Chronosphere AI review/);
});

test("anchors findings only when the new line is present in the diff", () => {
  const files = parseUnifiedDiff(diff);
  const finding = {
    file: "src/math.ts", line: 2, severity: "high", category: "correctness", title: "Finding", description: "Description", suggestion: "Suggestion",
  };
  assert.deepEqual(findingAnchor(files, finding), { path: "src/math.ts", line: 2, side: "RIGHT", changedIndex: 2 });
  assert.deepEqual(findingsAtNewLine([finding], "src/math.ts", 2), [finding]);
  assert.deepEqual(findingsAtNewLine([finding], "src/math.ts", null), []);
  assert.equal(isFindingStaged([], finding, files), false);
  assert.equal(isFindingStaged([{
    id: "draft-1", path: "src/math.ts", line: 2, side: "RIGHT", body: findingToCommentBody(finding), step: 0,
  }], finding, files), true);
  assert.equal(findingAnchor(files, {
    file: "src/math.ts", line: 99, severity: "high", category: "correctness", title: "Finding", description: "Description", suggestion: "Suggestion",
  }), null);
});
