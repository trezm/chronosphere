import type { DiffFile, PendingComment, ReviewFinding } from "./types";

const SEVERITY_ORDER = ["critical", "high", "medium", "low"] as const;

/** Stable, URL-safe target for a new-side line, unique across files in the diff. */
export function diffLineAnchorId(path: string, line: number): string {
  return `diff-line-${encodeURIComponent(path).replace(/_/g, "%5F").replace(/%/g, "_")}-R${line}`;
}

export function parseDiffLineAnchor(hash: string): { path: string; line: number } | null {
  try {
    const id = decodeURIComponent(hash.replace(/^#/, ""));
    const match = /^diff-line-(.+)-R([1-9]\d*)$/.exec(id);
    if (!match) return null;
    const line = Number(match[2]);
    return Number.isSafeInteger(line) ? { path: decodeURIComponent(match[1].replace(/_/g, "%")), line } : null;
  } catch {
    return null;
  }
}

export function sortFindings(findings: ReviewFinding[]): ReviewFinding[] {
  return [...findings].sort((left, right) => {
    const severity = SEVERITY_ORDER.indexOf(left.severity) - SEVERITY_ORDER.indexOf(right.severity);
    if (severity !== 0) return severity;
    if (left.file !== right.file) return left.file.localeCompare(right.file);
    return left.line - right.line;
  });
}

export function findingToCommentBody(finding: ReviewFinding): string {
  const sections = [
    `**${finding.severity.toUpperCase()} · ${finding.category}** — ${finding.title}`,
    "",
    finding.description,
  ];
  if (finding.suggestion) sections.push("", "**Suggestion**", "", finding.suggestion);
  sections.push("", "<sub>Generated by Chronosphere AI review.</sub>");
  return sections.join("\n").trim();
}

export function findingAnchor(files: DiffFile[], finding: Pick<ReviewFinding, "file" | "line">): {
  path: string;
  line: number;
  side: "RIGHT";
  changedIndex: number | null;
} | null {
  const file = files.find((candidate) => candidate.path === finding.file);
  const line = file?.hunks.flatMap((hunk) => hunk.lines).find((candidate) => candidate.newLine === finding.line);
  return line ? { path: finding.file, line: finding.line, side: "RIGHT", changedIndex: line.changedIndex } : null;
}

export function findingsAtNewLine(
  findings: ReviewFinding[],
  path: string,
  newLine: number | null,
): ReviewFinding[] {
  if (newLine === null) return [];
  return findings.filter((finding) => finding.file === path && finding.line === newLine);
}

export function isFindingStaged(
  comments: PendingComment[],
  finding: ReviewFinding,
  files: DiffFile[],
): boolean {
  const anchor = findingAnchor(files, finding);
  if (!anchor) return false;
  const body = findingToCommentBody(finding);
  return comments.some((comment) =>
    comment.path === anchor.path
    && comment.line === anchor.line
    && comment.side === anchor.side
    && comment.body === body
  );
}
